namespace ItchDB.Web.Services;

/// <summary>Tooltip texts: how every metric is calculated and what it means.</summary>
public static class Formulas
{
    public sealed record Tip(string Title, string Formula, string Text);

    public static Tip Median(int min) => new("Медиана оценок",
        $"median(оценки | оценок ≥ {min})",
        "Типичное число оценок у игры, которую хоть кто-то заметил. У большинства игр itch.io оценок нет, поэтому игры ниже порога не учитываются. Оценки — видимая часть аудитории: их оставляет примерно 1 игрок из 100.");

    public static Tip AdjMedian => new("Сглаженная медиана",
        "adj = (n·медиана сегмента + k·медиана itch.io) / (n + k)",
        "n — игр сегмента с оценками выше порога, k — сила сглаживания (настройка). Маленькие сегменты притягиваются к общей медиане, чтобы 3 удачные игры не делали нишу «самой востребованной».");

    public static Tip Mean(int min) => new("Среднее число оценок",
        $"mean(оценки | оценок ≥ {min})",
        "Среднее арифметическое по тем же играм, что и медиана. Медиана на itch.io часто равна 1 или 2: половина игр еле заметна, и соседние теги слипаются. Среднее учитывает хиты и лучше их разделяет.");

    public static Tip AdjMean => new("Сглаженное среднее",
        "adj = (n·среднее сегмента + k·среднее itch.io) / (n + k)",
        "n — игр сегмента с оценками выше порога, k — сила сглаживания. Маленькая выборка притягивается к общему среднему, чтобы пара хитов не делала нишу самой востребованной.");

    public static Tip Quantiles => new("P75 / P90",
        "75-й и 90-й перцентили числа оценок",
        "Сколько набирают лучшие 25% и 10% игр сегмента — потолок, до которого реально дорасти.");

    public static Tip Success(int threshold) => new("Шанс успеха",
        $"P = игр с ≥ {threshold} оценками / все игры сегмента на itch.io\n95%: интервал Уилсона",
        "Знаменатель — «(N results)» фильтра на itch.io, включая игры без оценок, когда в шапке включено «0 оценок». Выключенный переключатель считает шанс только среди игр с хотя бы одной оценкой. Интервал Уилсона показывает неопределённость; для рейтинга берётся его нижняя граница. Медиана от переключателя не зависит.");

    public static Tip Competition => new("Конкуренция",
        "игр в сегменте на itch.io; перцентиль log(1 + N) среди сегментов",
        "Сколько игр борется за ту же аудиторию. При включённом «0 оценок» это счётчик «(N results)» фильтра или число проектов со страницы /tags, вместе с играми без оценок. При выключенном — только игры, у которых уже есть оценка.");

    public static Tip Opportunity(double wd, double ws, double wc, double wt, bool mean = false) => new("Opportunity score",
        $"100 · ({wd:0.##}·Спрос + {ws:0.##}·Успех + {wc:0.##}·(1 − Конкуренция) + {wt:0.##}·Тренд) / Σw",
        "Каждый компонент — перцентиль сегмента среди остальных (0…1): спрос — " +
        (mean ? "среднее число оценок, сглаженное к itch.io" : "типичное число оценок (геометрическое среднее, сглаженное к itch.io)") +
        ", успех — нижняя граница шанса успеха, конкуренция — число игр, тренд — рост доли среди успешных игр. Веса меняются в настройках.");

    public static Tip Quadrant => new("Квадрант",
        "спрос ≥ медианы сегментов? × конкуренция ≥ медианы сегментов?",
        "Голубой океан — спрос высокий, игр мало. Красный океан — спрос высокий, игр много. Тихая ниша — мало и того и другого. Ловушка — игр много, спрос низкий.");

    public static Tip Trend(string? cohorts) => new("Тренд",
        "(доля сегмента среди успешных игр свежих лет) / (доля среди успешных игр двумя годами раньше) − 1",
        $"Растёт ли ниша среди игр, которые набрали порог оценок{(cohorts is null ? "" : $": {cohorts}")}. Сравниваются доли, поэтому общий рост itch.io не искажает тренд.");

    public static Tip Entry => new("Порог входа",
        "медиана оценок игр на 1-й странице «Популярного» по тегу",
        "Сколько оценок сейчас у игр, которые видны на первой странице тега. Первая страница — главный источник трафика внутри itch.io.");

    public static Tip WeightedRating(int m) => new("Взвешенный рейтинг",
        $"WR = v/(v+m)·R + m/(v+m)·C,  m = {m}",
        "R — средняя оценка игры, v — число оценок, C — средняя оценка по itch.io. Игры с 3 оценками по 5★ не обгоняют игры с сотнями оценок по 4,7★ (формула IMDb).");

    public static Tip Hot => new("Горячее",
        "(Δоценок + a·Δкомментариев + b·рост позиции) · 7 / дней окна / (возраст + 2)^g",
        "Прирост за последние до 7 дней между ежедневными снимками, приведённый к недельному темпу. Деление на возраст поднимает новые игры, которые быстро набирают аудиторию. Нужны снимки минимум за 2 дня.");

    public static Tip Audience => new("Оценка аудитории",
        "просмотры ≈ оценки / доля оценивающих (по умолчанию 1%, диапазон 0,5–2%)",
        "itch.io не показывает просмотры и скачивания чужих игр. С API-ключом в «Моя игра» доли считаются по вашим реальным играм.");

    public static Tip Uplift => new("Uplift",
        "P(успех | признак) / P(успех | без признака), 95% ДИ логарифмическим методом",
        "Во сколько раз чаще игры с признаком набирают порог оценок. Это корреляция: признак может просто сопутствовать более старым или более крупным проектам.");

    public static Tip Multiplier => new("Множитель (модель)",
        "exp(β) из OLS: ln(1 + оценки) ~ ln(1 + возраст) + ln(1 + скриншоты) + признаки",
        "Во сколько раз больше оценок у игр с признаком при прочих равных, включая возраст. Звёздочка — 95% интервал не включает ×1. Корреляция ≠ причинность.");

    public static Tip Lift => new("Лифт сочетания",
        "медиана(A и B) / max(медиана A, медиана B)",
        "Лифт > 1 — вместе теги работают лучше, чем каждый по отдельности.");
}
